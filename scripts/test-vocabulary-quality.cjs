const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'vocabulary-quality.js'),'utf8'),sandbox);
vm.runInNewContext(fs.readFileSync(path.join(root,'lexicon-valenciano.js'),'utf8'),sandbox);
const audit=sandbox.window.ExaminaVocabularyQuality.audit;
const translator=sandbox.window.ExaminaValencianGloss;
const data=JSON.parse(fs.readFileSync(path.join(root,'data/lemmas/teacher-forms.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const start=html.indexOf('let vocab=')+'let vocab='.length;
assert.ok(start>10,'No se encuentra el banco de la aplicación');
const bank=JSON.parse(html.slice(start,html.indexOf(';',start)));
for(const m of html.matchAll(/vocab\.push\(\.\.\.(\[.*\])\);/g))bank.push(...JSON.parse(m[1]));
let total=0;
for(const [course,expected] of [['lat1',1107],['lat4',541],['gr1',399]]){
 const result=audit(data,bank,course,translator),t=result.totals;
 assert.equal(result.schema,1);
 assert.equal(t.rows,expected,course+': se han perdido entradas');
 assert.equal(t.rows,t.documented+t.proposalsOnly+t.citationsOnly+t.noIndex);
 assert.equal(t.spanishMissing,0,course+': faltan glosas castellanas');
 assert.equal(t.valencianMissing,0,course+': faltan glosas valencianas');
 assert.ok(t.documented>0&&t.documented<t.rows,'La auditoría no debe declarar todo el banco verificado');
 assert.equal(t.readyForMorphology,t.documented,'Sólo se usan lemas con traducciones disponibles');
 assert.ok(result.units.length>1,'Deben existir unidades diferenciadas');
 const perUnitReferences=result.units.reduce((n,u)=>n+u.rows,0);
 if(course==='gr1'){
  assert.ok(perUnitReferences>=expected,'Las etiquetas UD griegas pueden asociarse a varias unidades');
  assert.ok(t.unassigned>0,'No debe inventarse unidad para todo el banco general griego');
  assert.ok(result.units.some(u=>/^UD/.test(u.unit)),'Deben recuperarse unidades griegas contrastadas');
 }else assert.ok(perUnitReferences>=expected,'Una ficha puede corresponder a un intervalo de unidades');
 assert.ok(result.units.every(u=>u.rows===u.documented+u.proposalsOnly+u.citationsOnly+u.noIndex));
 assert.ok(result.reviewQueue.length>=t.rows-t.documented);
 assert.ok(result.reviewQueue.every(r=>r.status!=='documented'),'No mandar formas documentadas a revisión sin motivo');
 total+=t.rows;
 console.log(course+': '+JSON.stringify(t)+'; '+result.units.length+' unidades');
}
assert.equal(total,2047);
const mock={vocabulary:{lat:{amo:{lat1:{entry:'amo, amavi, amatum (1ª)'}}}},rows:{lat:[['amo','amamus','V;PRS',2]]}};
const proposal=audit(mock,[{course:'latin1',unit:'UD1',entry:'amo, amavi, amatum (1ª)',meaning:'amar',meaning_va:'amar'}],'lat1');
assert.equal(proposal.totals.documented,0,'No elevar propuestas regulares a verificadas');
assert.equal(proposal.totals.proposalsOnly,1);
mock.rows.lat[0][3]=5;
const contrast=audit(mock,[{course:'latin1',unit:'UD1',entry:'amo, amavi, amatum (1ª)',meaning:'amar',meaning_va:'amar'}],'lat1');
assert.equal(contrast.totals.documented,1,'Admitir sólo una fuente contrastada');
console.log('Auditoría de vocabulario por unidades: verificaciones conservadoras superadas.');
