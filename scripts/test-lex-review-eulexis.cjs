'use strict';
const {readFileSync}=require('node:fs');
const {join}=require('node:path');
const {Script,createContext}=require('node:vm');
const assert=require('node:assert/strict');
const root=join(__dirname,'..');
const html=readFileSync(join(root,'index.html'),'utf8');
const vocab=readFileSync(join(root,'vocabulary-generator.js'),'utf8');
const staged=JSON.parse(readFileSync(join(root,'data/fonetica/evolutio-faciles-por-aprobar.json'),'utf8'));
assert.match(html,/selectedChoices\.map\(row=>'<div class="exam-review-line"/);
assert.match(html,/pending\.map\(row=>'<div class="exam-review-line"/);
assert.match(html,/\.exam-review-line::before/);
assert.match(html,/\.exam-gloss-review-workspace \.exam-gloss-reset/);
assert.doesNotMatch(html,/<small class="phonetic-origin-label" contenteditable="false">/);
assert.doesNotMatch(html,/adaptaciones cultas etiquetadas en el examen y en Word/);
assert.match(html,/x\.valencianPrefixEligible===false\|\|\/\\s\/u\.test/);
assert.match(vocab,/window\.ExaminaGreekEulexisCitation\?\./);
const helper=html.match(/function greekEulexisCitation\(value\)\{[\s\S]*?\n\}\nwindow\.ExaminaGreekEulexisCitation=/);
assert.ok(helper,'No se encuentra la función para enunciados de Eulexis');
const ctx=createContext({window:{}});
new Script(helper[0]+'greekEulexisCitation;', {filename:'eulexis-helper.js'}).runInContext(ctx);
const school=ctx.window.ExaminaGreekEulexisCitation;
assert.equal(school('λόγος, -ου, ὁ'),'λόγος, -ου');
assert.equal(school('θάλαττα, -ης, ἡ'),'θάλαττα, -ης');
assert.equal(school('ἡ ἀγορά, -ᾶς, ἡ'),'ἀγορά, -ᾶς');
assert.equal(school('δῶρον, -ου, τό'),'δῶρον, -ου');
assert.equal(school('πόλις, -εως, ἡ'),'πόλις, -εως, ἡ');
assert.equal(school('παῖς, -δός, ὁ'),'παῖς, -δός, ὁ');
assert.equal(school('λύω'),'λύω');
assert.equal(school('ἐλπίς, -ίδος, ἡ'),'ἐλπίς, -ίδος, ἡ');
assert.equal(staged.status,'PROPUESTA_NO_ACTIVA_PENDIENTE_APROBACION_DOCENTE');
assert.equal(staged.items.length,186);
assert.equal(new Set(staged.items.map(x=>x.id)).size,186);
assert.equal(staged.coverage.length,13);
assert.equal(staged.missingRules.length,7);
assert.ok(staged.items.every(x=>x.dificultad==='facil'&&
 !/^\p{Lu}/u.test(x.castellano)&&x.normas.length>0));
assert.ok(!html.includes('data/fonetica/evolutio-faciles-por-aprobar.json'),
 'No activar el lote pendiente de aprobación');
console.log('Revisión léxica y Eulexis: 186 candidatas no activas, citas y controles, correcto.');
