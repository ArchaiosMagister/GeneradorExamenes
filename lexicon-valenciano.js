 const exact=new Map(Object.entries(translations));
 const normalized=value=>String(value||'').trim().replace(/[‘’“”'"]/gu,'').replace(/\\s+/gu,' ');
 const lower=value=>normalized(value).toLocaleLowerCase('es');
 function part(raw){
  const text=normalized(raw),k=lower(text);
  if(exact.has(k))return exact.get(k);
  // Las aclaraciones de caso, género, número y regímenes no son significados.
  const note=text.match(/^(.+?)\s*\(([^)]*)\)$/u);
  if(note){
   const v=part(note[1]);if(!v)return null;
   const notes={'masc.':'masc.','fem.':'fem.','sing.':'sing.','pl.':'pl.','m.':'m.','f.':'f.','adv.':'adv.','conj.':'conj.','prep.':'prep.'};
   return v+' ('+(notes[note[2]]||note[2])+')';
  }
  // Nombres propios cuya grafía valenciana coincide con la castellana.
  if(/^\p{Lu}/u.test(text)&&!text.includes(' ')&&/^[\p{L}\p{M}·-]+$/u.test(text))return text;
  const elements=text.split(/\s+/u);
  if(elements.length>1){
   const translated=elements.map(word=>{
    const punct=word.match(/^([^\p{L}]*)(.*?)([^\p{L}]*)$/u);
    if(!punct)return null;
    const v=exact.get(lower(punct[2]));return v?punct[1]+v+punct[3]:null;
   });
   if(translated.every(Boolean))return translated.join(' ');
  }
  return null;
 }
 function lookup(raw){
  const text=normalized(raw);
  if(!text||/^\[(?:traducci[oó]n|traducci[oó]) pendiente/i.test(text))return {value:'',ready:false};
  const direct=part(text);if(direct)return {value:direct,ready:true};
  // Los repertorios presentan alternativas entre comillas simples o comas.
  // Traducir cada acepción antes de reunirlas evita confundir homógrafos.
  const chunks=text.split(/\s*(?:,\s*|;\s*|\s*[|]\s*)/u);
  if(chunks.length>1){
   const result=chunks.map(part);
   if(result.every(Boolean))return {value:result.join(', '),ready:true};
  }
  return {value:'',ready:false};
 }
 function forEntry(item,lang){
  if(lang!=='va')return {value:String(item?.meaning||''),ready:!!String(item?.meaning||'').trim(),source:'docente'};
  if(item?.meaning_va&&String(item.meaning_va).trim())return {value:String(item.meaning_va).trim(),ready:true,source:'docente-valenciano'};
  const result=lookup(item?.meaning);return {...result,source:result.ready?'diccionario-valenciano':'pendiente'};
 }
